package services;

import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

import java.io.File;
import java.util.UUID;

import org.junit.After;
import org.junit.Before;
import org.junit.Test;

import datasets.DatasetConnector;
import models.Dataset;
import models.DatasetType;
import models.Person;
import models.Project;
import play.Application;
import play.inject.guice.GuiceApplicationBuilder;
import play.test.WithApplication;
import services.maintenance.DatabaseBackupService;

public class DatabaseBackupServiceTest extends WithApplication {

	private DatasetConnector datasetConnector;
	private DatabaseBackupService backupService;

	@Override
	protected Application provideApplication() {
		return new GuiceApplicationBuilder().configure("db.default.driver", "org.h2.Driver")
				.configure("db.default.url", "jdbc:h2:mem:play;DB_CLOSE_DELAY=-1")
				.configure("play.evolutions.db.default.autoApply", true).build();
	}

	@Before
	public void setUp() {
		datasetConnector = app.injector().instanceOf(DatasetConnector.class);
		backupService = app.injector().instanceOf(DatabaseBackupService.class);
	}

	@After
	public void tearDown() {
		// Clean up any files generated by backup or stats during test
		File currentStats = new File("current_stats.json");
		if (currentStats.exists()) {
			currentStats.delete();
		}
	}

	private Person createPerson(String prefix) {
		Person person = new Person();
		person.setUser_id(UUID.randomUUID().toString());
		person.setFirstname(prefix);
		person.setLastname("User");
		person.setEmail(prefix.toLowerCase() + "_" + UUID.randomUUID().toString().substring(0, 8) + "@example.com");
		person.save();
		return person;
	}

	@Test
	public void testDatasetMigrationExecutionAndIdempotency() {
		Person user = createPerson("Migrate");
		Project project = Project.create("Test Migration Project", user, "Intro", false, false);
		project.save();

		Dataset ds = datasetConnector.create("Timeseries DS", DatasetType.TIMESERIES, project, "Test DS", "Target",
				"true");
		ds.save();

		// Initially not completed
		backupService.setMigrationCompleted(false);
		assertFalse(backupService.isMigrationCompleted());

		// Execute migration
		backupService.performDatasetMigration();
		assertTrue(backupService.isMigrationCompleted());

		// Subsequent run without force should skip without error
		backupService.performDatasetMigration(false);
		assertTrue(backupService.isMigrationCompleted());

		// Force run should also succeed
		backupService.performDatasetMigration(true);
		assertTrue(backupService.isMigrationCompleted());
	}

	@Test
	public void testAdminDatasetMigrationTrigger() {
		backupService.setMigrationCompleted(false);
		assertFalse(backupService.isMigrationCompleted());

		backupService.adminDatasetMigration();
		assertTrue(backupService.isMigrationCompleted());
	}
}
